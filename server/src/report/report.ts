import type { PageRunState, RunRecord, RunResult } from '@refit/shared';
import { duration } from '../util/time.js';

export interface ReportInput {
  run: RunRecord;
  result: RunResult;
  providerLabel: string;
  reverts: Array<{ file: string; reason: string; pageId?: string }>;
  version: string;
}

const STATUS_LABEL: Record<PageRunState['status'], string> = {
  queued: 'Not started',
  working: 'In progress',
  reviewing: 'In design review',
  done: 'Done',
  flagged: 'Flagged',
  skipped: 'Skipped',
};

/** The run report: written to data/runs/<runId>/report.md and used as the pull request description. */
export function buildReport(input: ReportInput): string {
  const { run, result } = input;
  const lines: string[] = [];
  const total = run.pages.length;
  lines.push(`# Front-end modernization: ${run.appName}`, '');
  lines.push(
    `Refit modernized the front end of **${run.appName}** with ${input.providerLabel}` +
      (run.branch ? ` on branch \`${run.branch}\`` : '') +
      (run.baseBranch ? ` (from \`${run.baseBranch}\`${run.baseCommit ? ` at ${run.baseCommit.slice(0, 8)}` : ''})` : '') +
      '. Only templates, styles and presentation code changed; services, API calls, routing, auth and configuration are protected.',
    '',
  );

  lines.push('## Summary', '', '| | |', '|---|---|');
  const upgrade = run.steps.find((step) => step.id === 'upgrade');
  const design = run.steps.find((step) => step.id === 'design-system');
  if (upgrade?.detail) lines.push(`| Angular | ${upgrade.status === 'failed' ? `**${upgrade.detail}**` : upgrade.detail} |`);
  if (design?.detail) lines.push(`| Design system | ${design.status === 'failed' ? `**${design.detail}**` : design.detail} |`);
  lines.push(`| Pages modernized | ${result.pagesDone} of ${total} |`);
  lines.push(`| Flagged for a developer | ${result.pagesFlagged} |`);
  lines.push(`| Skipped | ${result.pagesSkipped} |`);
  lines.push(`| Final build | ${result.build === 'passed' ? 'Passed' : result.build === 'failed' ? '**Failed**' : 'Not run'} |`);
  lines.push(`| Unit tests | ${testsLabel(result.tests)} |`);
  lines.push(`| API calls unchanged | ${result.apiUnchanged === null ? 'Not checked' : result.apiUnchanged ? 'Yes, on every checked page' : '**No**, see flagged pages'} |`);
  lines.push(`| Protected files reverted | ${result.protectedReverts} |`);
  lines.push(`| AI cost | ${result.requests > 0 ? `${result.requests} requests` : `$${result.costUsd.toFixed(2)}`} |`);
  lines.push(`| Duration | ${duration(result.durationMs)} |`, '');

  const flagged = run.pages.filter((page) => page.status === 'flagged');
  if (flagged.length > 0) {
    lines.push('## Needs attention', '');
    for (const page of flagged) lines.push(`- **${page.name}** (\`${page.route}\`): ${page.note ?? 'flagged'}`);
    lines.push('');
  }

  if (design?.status === 'done') {
    lines.push(
      '## Design system',
      '',
      'Refit installed PrimeNG and wrote the brand into `src/app/theme`: `brand-preset.ts` (the PrimeNG preset), `brand.css` (variables and layout classes) and `BRAND.md` (how to use them). Change the brand in Refit and regenerate these files instead of editing them by hand.',
      '',
    );
  }

  lines.push('## Pages', '');
  for (const page of run.pages) {
    lines.push(`### ${page.name} (\`${page.route}\`): ${STATUS_LABEL[page.status]}`, '');
    if (page.note) lines.push(`_${page.note}_`, '');
    const report = page.report;
    if (report) {
      if (report.summary) lines.push(report.summary, '');
      if (report.changes.length > 0) {
        lines.push('**What changed**', '', ...report.changes.map((change) => `- ${change}`), '');
      }
      if (report.concerns.length > 0) {
        lines.push('**Please double-check**', '', ...report.concerns.map((concern) => `- ${concern}`), '');
      }
      if (!report.structured) lines.push('_The agent did not return a structured report for this page._', '');
    }
    if (page.apiDiff && (page.apiDiff.added.length > 0 || page.apiDiff.removed.length > 0)) {
      lines.push('**API calls changed**', '');
      for (const call of page.apiDiff.added) lines.push(`- New: \`${call}\``);
      for (const call of page.apiDiff.removed) lines.push(`- Missing: \`${call}\``);
      lines.push('');
    }
  }

  if (input.reverts.length > 0) {
    lines.push('## Protected files the agent touched (reverted)', '');
    lines.push('Refit put these files back exactly as they were. Nothing of this is in the branch.', '');
    for (const revert of input.reverts) {
      const page = run.pages.find((candidate) => candidate.pageId === revert.pageId);
      lines.push(`- \`${revert.file}\`${page ? ` (${page.name})` : ''}: ${revert.reason}`);
    }
    lines.push('');
  }

  if (result.sensitiveChanges.length > 0) {
    lines.push('## Sensitive files changed (please review)', '');
    lines.push(...result.sensitiveChanges.map((file) => `- \`${file}\``), '');
  }

  lines.push('---', '', `_Generated by Refit ${input.version} on ${new Date().toISOString().slice(0, 10)}._`, '');
  return lines.join('\n');
}

function testsLabel(tests: RunResult['tests']): string {
  switch (tests) {
    case 'passed':
      return 'Passed';
    case 'failed':
      return '**Failed**';
    case 'no-regressions':
      return 'No new failures (some tests already failed before)';
    case 'regressions':
      return '**New failures**';
    default:
      return 'Not run';
  }
}
